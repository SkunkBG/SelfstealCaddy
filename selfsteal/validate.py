@dataclass
class Probe:
    path: str
    status: int
    content_type: Optional[object] = None   # str, or a tuple of acceptable values
    method: str = "GET"
    json_body: bool = False
    location_prefix: Optional[str] = None
    location_excludes: Optional[str] = None


class _PinnedConnection(http.client.HTTPSConnection):
    """Connect to a fixed address while presenting the site's own hostname.

    The backend is a name-based virtual host bound to loopback, so a probe has
    to dial 127.0.0.1 but still send SNI and Host for the real domain.  The
    first version of this checker connected straight to the IP; Python omits
    SNI for an IP literal, Caddy then had no site to match, and every probe
    died with TLSV1_ALERT_INTERNAL_ERROR while the site itself was fine.
    """

    def __init__(self, host, port, connect_addr, context, timeout):
        super().__init__(host, port, context=context, timeout=timeout)
        self._connect_addr = connect_addr

    def connect(self):
        self.sock = socket.create_connection(
            (self._connect_addr, self.port), self.timeout)
        self.sock = self._context.wrap_socket(self.sock, server_hostname=self.host)


def _connection(base: str, connect_addr: Optional[str], timeout: float):
    parts = urlsplit(base)
    host = parts.hostname or "127.0.0.1"
    port = parts.port or (443 if parts.scheme == "https" else 80)
    if parts.scheme != "https":
        return http.client.HTTPConnection(connect_addr or host, port, timeout=timeout)
    context = ssl.create_default_context()
    # The backend certificate is for the public domain and is served over
    # loopback; verifying it here would test DNS, not the site.
    context.check_hostname = False
    context.verify_mode = ssl.CERT_NONE
    if connect_addr:
        return _PinnedConnection(host, port, connect_addr, context, timeout)
    return http.client.HTTPSConnection(host, port, context=context, timeout=timeout)


def _request(base: str, probe: "Probe", timeout: float = 8.0,
             connect_addr: Optional[str] = None) -> Tuple[int, dict, bytes]:
    conn = _connection(base, connect_addr, timeout)
    try:
        conn.request(probe.method, probe.path, headers={
            "Host": urlsplit(base).hostname or "localhost",
            "User-Agent": "Mozilla/5.0 (compatible; site-check/1.0)",
            "Accept": "*/*",
            "Connection": "close",
        })
        resp = conn.getresponse()
        # Lower-cased keys: HTTP header names are case-insensitive, and a check
        # for "Server" that a different capitalisation slips past is worse than
        # no check at all.
        headers = {k.lower(): v for k, v in resp.getheaders()}
        return resp.status, headers, resp.read()
    finally:
        conn.close()


def wait_until_ready(base: str, connect_addr: Optional[str] = None,
                     timeout: float = 45.0) -> Optional[str]:
    """Poll until the backend answers, or return why it never did.

    A certificate may still be issuing when the installer reaches this point,
    so a single early failure is not evidence of a broken site.
    """
    deadline = time.monotonic() + timeout
    last = "no attempt made"
    while time.monotonic() < deadline:
        try:
            _request(base, Probe("/", 200), timeout=5.0, connect_addr=connect_addr)
            return None
        except Exception as exc:                       # noqa: BLE001 - reported
            last = str(exc)
            time.sleep(2.0)
    return last


def default_probes(endpoints: List[str], pages: List[str]) -> List[Probe]:
    probes = [Probe("/", 200, "text/html")]
    probes += [Probe(p, 200, "text/html") for p in pages if p != "/"]
    probes += [Probe(e, 200, "application/json", json_body=True) for e in endpoints]
    probes += [
        Probe("/robots.txt", 200, "text/plain"),
        Probe("/sitemap.xml", 200, ("application/xml", "text/xml")),
        Probe("/.well-known/security.txt", 200, "text/plain"),
        Probe("/favicon.ico", 200),
        Probe("/favicon.svg", 200, "image/svg+xml"),
        Probe("/style.css", 200, "text/css"),
        Probe("/does-not-exist-8f2c", 404, "text/html"),
        Probe("/.env", 404),
        Probe("/.git/HEAD", 404),
        Probe("/_api/api", 404),
        Probe("/", 200, method="HEAD"),
    ]
    if endpoints:
        probes += [
            Probe("/status.json", 200, "application/json", json_body=True),
            Probe(endpoints[0], 405, method="POST", json_body=True),
            Probe(endpoints[0], 204, method="OPTIONS"),
        ]
        api_root = next((e for e in endpoints if e.startswith("/api/")), None)
        if api_root:
            probes.append(Probe(api_root + "/definitely-missing", 404,
                                "application/json", json_body=True))
    return probes


def public_http_probes(domain: str, https_port: int = 8443) -> List[Probe]:
    """Probes for the :80 listener — the only Caddy surface facing the internet.

    It used to be checked by nobody.  The backend strips ``Server`` and
    ``Alt-Svc``; the redirect in front of it did not, so a single unauthenticated
    ``curl http://domain/`` identified the stack that everything behind it goes
    to some trouble to hide.  The Location assertions cover the other half of
    the contract: the redirect must reach the public 443 and must never disclose
    the backend port.
    """
    redirect_to = f"https://{domain}"
    return [
        Probe("/", 301, location_prefix=redirect_to,
              location_excludes=f":{https_port}"),
        Probe("/does-not-exist-8f2c", 301, location_prefix=redirect_to,
              location_excludes=f":{https_port}"),
        Probe("/.env", 301, location_prefix=redirect_to),
    ]


def check_live(base: str, probes: List[Probe],
               connect_addr: Optional[str] = None) -> Report:
    report = Report()
    unreachable = wait_until_ready(base, connect_addr)
    if unreachable is not None:
        report.checks += 1
        report.failures.append(
            f"backend at {base} did not answer within the timeout: {unreachable}")
        return report
    for probe in probes:
        try:
            status, headers, body = _request(base, probe, connect_addr=connect_addr)
        except Exception as exc:                      # noqa: BLE001 - reported
            report.failures.append(f"{probe.method} {probe.path}: {exc}")
            report.checks += 1
            continue
        report.check(status == probe.status,
                     f"{probe.method} {probe.path}: expected {probe.status}, "
                     f"got {status}")
        if probe.content_type:
            actual = headers.get("content-type", "")
            # A tuple means "any of these is correct". Caddy serves sitemap.xml
            # as application/xml; older versions said text/xml. Both are right,
            # and a checker that insists on one of them fails every real install
            # the day the server changes its mind.
            wanted = (probe.content_type if isinstance(probe.content_type, tuple)
                      else (probe.content_type,))
            report.check(any(candidate in actual for candidate in wanted),
                         f"{probe.method} {probe.path}: expected Content-Type "
                         f"{' or '.join(wanted)}, got {actual!r}")
        report.check("server" not in headers,
                     f"{probe.method} {probe.path}: Server header present "
                     f"({headers.get('server')!r}) — backend is identifiable")
        report.check("alt-svc" not in headers,
                     f"{probe.method} {probe.path}: Alt-Svc advertised")
        location = headers.get("location", "")
        if probe.location_prefix:
            report.check(location.startswith(probe.location_prefix),
                         f"{probe.method} {probe.path}: expected Location under "
                         f"{probe.location_prefix}, got {location!r}")
        if probe.location_excludes:
            report.check(probe.location_excludes not in location,
                         f"{probe.method} {probe.path}: Location leaks "
                         f"{probe.location_excludes!r} ({location!r})")
        if probe.json_body and probe.method != "HEAD" and body:
            try:
                json.loads(body.decode("utf-8"))
            except (ValueError, UnicodeDecodeError) as exc:
                report.failures.append(
                    f"{probe.method} {probe.path}: body is not valid JSON ({exc})")
                report.checks += 1
    return report
