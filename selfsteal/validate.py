"""Validation.

Two layers.  ``check_tree`` inspects what was generated on disk and needs no
running server; it is what CI runs.  ``check_live`` speaks HTTP to a running
Caddy and asserts the contract the Caddyfile is supposed to implement — status
codes, content types, method semantics and the absence of the backend's
identity.

The checks that matter most are the negative ones: no external resource, no
internal address, no secret-shaped string and no marker identifying the
generator.  A decoy that phones out to a font CDN has failed regardless of how
convincing it looks.
"""

from __future__ import annotations

import http.client
import json
import re
import socket
import ssl
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import List, Optional, Tuple
from urllib.parse import urlsplit

EXTERNAL_URL_RE = re.compile(
    r"""(?:src|href|action|content)\s*=\s*["'](?:https?:)?//([^/"']+)""",
    re.IGNORECASE,
)
IMPORT_RE = re.compile(r"@import\s+(?:url\()?['\"]?(?:https?:)?//", re.IGNORECASE)
PRIVATE_IP_RE = re.compile(
    r"\b(?:127\.\d+\.\d+\.\d+|10\.\d+\.\d+\.\d+|192\.168\.\d+\.\d+"
    r"|172\.(?:1[6-9]|2\d|3[01])\.\d+\.\d+|0\.0\.0\.0|::1)\b"
)
LOCALHOST_RE = re.compile(r"\blocalhost\b", re.IGNORECASE)
SECRET_RE = re.compile(
    r"(?i)\b(?:api[_-]?key|secret[_-]?key|password|passwd|private[_-]?key|"
    r"bearer\s+[a-z0-9._-]{16,}|BEGIN\s+(?:RSA|OPENSSH|PRIVATE)\s+KEY)\b"
)
MARKER_RE = re.compile(r"(?i)selfsteal|remnawave|xray|reality|generated by")

TEXT_SUFFIXES = {".html", ".css", ".json", ".xml", ".txt", ".svg"}


@dataclass
class Report:
    checks: int = 0
    failures: List[str] = field(default_factory=list)
    warnings: List[str] = field(default_factory=list)

    def ok(self) -> bool:
        return not self.failures

    def check(self, condition: bool, message: str) -> bool:
        self.checks += 1
        if not condition:
            self.failures.append(message)
        return condition

    def warn(self, condition: bool, message: str) -> None:
        self.checks += 1
        if not condition:
            self.warnings.append(message)

    def merge(self, other: "Report") -> "Report":
        self.checks += other.checks
        self.failures.extend(other.failures)
        self.warnings.extend(other.warnings)
        return self


def check_tree(webroot: Path, domain: str) -> Report:
    report = Report()
    webroot = Path(webroot)

    required = ["index.html", "404.html", "style.css", "favicon.svg",
                "favicon.ico", "robots.txt", "sitemap.xml",
                ".well-known/security.txt"]
    for name in required:
        report.check((webroot / name).exists(), f"missing required file: {name}")

    ico = webroot / "favicon.ico"
    if ico.exists():
        blob = ico.read_bytes()
        report.check(blob[:4] == b"\x00\x00\x01\x00",
                     "favicon.ico is not a valid ICO container")
        report.check(len(blob) > 64, "favicon.ico is implausibly small")

    for path in sorted(webroot.rglob("*")):
        if not path.is_file() or path.suffix not in TEXT_SUFFIXES:
            continue
        rel = path.relative_to(webroot).as_posix()
        if rel.startswith(".selfsteal"):
            continue
        try:
            text = path.read_text("utf-8")
        except (OSError, UnicodeDecodeError):
            report.failures.append(f"{rel}: not readable as UTF-8")
            continue

        for host in EXTERNAL_URL_RE.findall(text):
            host = host.split(":")[0].lower()
            if host and host != domain:
                report.failures.append(f"{rel}: references external host {host}")
        report.check(not IMPORT_RE.search(text), f"{rel}: remote CSS @import")
        report.check(not PRIVATE_IP_RE.search(text),
                     f"{rel}: contains a private or loopback IP address")
        report.check(not LOCALHOST_RE.search(text), f"{rel}: mentions localhost")
        report.check(not SECRET_RE.search(text),
                     f"{rel}: contains a credential-shaped string")
        report.check(not MARKER_RE.search(text),
                     f"{rel}: leaks a generator or infrastructure marker")

        if path.suffix == ".json":
            try:
                json.loads(text)
            except ValueError as exc:
                report.failures.append(f"{rel}: invalid JSON ({exc})")
        if path.suffix == ".html":
            report.check("<html" in text.lower(), f"{rel}: missing <html>")
            report.check("</html>" in text.lower(), f"{rel}: unterminated document")
            report.check(text.lower().count("<body") == 1,
                         f"{rel}: expected exactly one <body>")

    sitemap = webroot / "sitemap.xml"
    if sitemap.exists():
        urls = re.findall(r"<loc>https://([^/]+)(/[^<]*)</loc>",
                          sitemap.read_text("utf-8"))
        report.check(bool(urls), "sitemap.xml lists no URLs")
        for host, url in urls:
            report.check(host == domain,
                         f"sitemap.xml references foreign host {host}")
            report.check(_resolves(webroot, url),
                         f"sitemap.xml lists {url}, which has no backing file")
            report.check(not url.startswith("/api"),
                         f"sitemap.xml lists API route {url}")

    robots = webroot / "robots.txt"
    if robots.exists():
        report.check("Sitemap:" in robots.read_text("utf-8"),
                     "robots.txt does not reference the sitemap")

    sec = webroot / ".well-known/security.txt"
    if sec.exists():
        body = sec.read_text("utf-8")
        report.check("Contact:" in body, "security.txt has no Contact field")
        report.check("Expires:" in body, "security.txt has no Expires field")

    return report


def _resolves(webroot: Path, url: str) -> bool:
    """Mirror the Caddy try_files chain for HTML routes."""
    rel = url.lstrip("/")
    if rel == "":
        return (webroot / "index.html").exists()
    candidates = [webroot / rel,
                  webroot / rel / "index.html",
                  webroot / (rel + ".html")]
    return any(c.is_file() for c in candidates)


